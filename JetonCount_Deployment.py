TOKENIZER_ID = "fromziro/Er-Tiny-1.3M"

model = AutoModel.from_pretrained(MODEL_ID, trust_remote_code=True, revision=REVISION)
model.eval()
tokenizer = AutoTokenizer.from_pretrained(TOKENIZER_ID, use_fast=True)

#the features we need
PUNCT = set(r""".,!?;:'"`~@#$%^&*()-_=+[]{}<>/\|""")
SYMB  = set(r"""@#$%^&*()-_=+[]{}<>/\|~`""")

def base_features(text: str, vocab_size: int):
    chars = len(text)
    words = re.findall(r"\b\w+\b", text, flags=re.UNICODE)
    n = len(words)
    avg = sum(len(w) for w in words) / n if n else 0.0
    longest = max((len(w) for w in words), default=0)
    p = sum(c in PUNCT for c in text) / chars if chars else 0.0
    s = sum(c in SYMB for c in text) / chars if chars else 0.0
    return [float(chars), float(n), avg, p, s, float(longest), float(vocab_size)]

