TARGET_VOCAB_SIZE = 199998 
MIN_CHARS_FOR_MODEL = 400         # roughly 70-80 words; below this we use heuristic

def predict_tokens(text, vocab_size=TARGET_VOCAB_SIZE):
    """Estimate token count. Returns the estimate, which method produced it, and debug info."""
    if not isinstance(text, str):
        raise TypeError("text must be a string")
    if text.strip() == "":
        return {"estimated_tokens": 0, "method": "empty", "approximate": False,
                "raw_prediction": None, "features": None}

    heuristic = max(1, round(len(text) / 4))

    if len(text) < MIN_CHARS_FOR_MODEL:
        return {"estimated_tokens": heuristic, "method": "heuristic_chars_div_4",
                "approximate": True, "raw_prediction": None, "features": None}

    feats = base_features(text, vocab_size)
    x = torch.tensor([feats], dtype=torch.float32)     
    with torch.inference_mode():
        raw = model(input_features=x).logits.item()

    if raw <= 0:    #making sure token amount is not negative                               
        return {"estimated_tokens": heuristic, "method": "heuristic_fallback",
                "approximate": True, "raw_prediction": raw, "features": None}

    return {"estimated_tokens": round(raw), "method": "jetoncount", "approximate": False,
            "raw_prediction": raw, "features": dict(zip(model.config.base_feature_names, feats))}

